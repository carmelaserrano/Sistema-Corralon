create or replace function public.fn_recalcular_total_oc()
returns trigger
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  v_oc uuid := coalesce(new.orden_compra_id, old.orden_compra_id);
begin
  update public.ordenes_compra
     set total = coalesce((
           select sum(subtotal) from public.detalle_orden_compra where orden_compra_id = v_oc
         ), 0)
   where id = v_oc;
  return null;
end;
$$;

