do $$
begin
  if to_regprocedure('public.usuario_tiene_permiso(text)') is null then
    raise exception
      'Falta public.usuario_tiene_permiso(text), definida en 0012. Aplicá esa migración primero o ajustá la firma en esta.';
  end if;
end $$;


