-- No se puede recibir más de lo pedido en la OC.
create or replace function public.fn_validar_cantidad_recibida()
returns trigger
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  v_pedido   numeric;
  v_recibido numeric;
begin
  if new.orden_compra_detalle_id is null then
    return new;
  end if;

  select cantidad into v_pedido
    from public.detalle_orden_compra where id = new.orden_compra_detalle_id;

  select coalesce(sum(dr.cantidad),0) into v_recibido
    from public.detalle_recepcion dr
    join public.recepciones r on r.id = dr.recepcion_id
   where dr.orden_compra_detalle_id = new.orden_compra_detalle_id
     and r.estado_recepcion <> 'anulada'
     and dr.id <> new.id;

  if v_recibido + new.cantidad > v_pedido then
    raise exception 'La cantidad recibida (%) supera la pedida en la Orden de Compra (%)',
      v_recibido + new.cantidad, v_pedido;
  end if;

  return new;
end;
$$;

drop trigger if exists trg_validar_cantidad_recibida on public.detalle_recepcion;
create trigger trg_validar_cantidad_recibida
  before insert or update on public.detalle_recepcion
  for each row execute function public.fn_validar_cantidad_recibida();


-- No se puede devolver más de lo recibido en esa línea.
create or replace function public.fn_validar_cantidad_devuelta()
returns trigger
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  v_recibido numeric;
  v_devuelto numeric;
begin
  select cantidad into v_recibido
    from public.detalle_recepcion where id = new.detalle_recepcion_id;

  select coalesce(sum(cantidad),0) into v_devuelto
    from public.detalle_devolucion
   where detalle_recepcion_id = new.detalle_recepcion_id and id <> new.id;

  if v_devuelto + new.cantidad > v_recibido then
    raise exception 'La cantidad devuelta (%) supera la recibida (%)',
      v_devuelto + new.cantidad, v_recibido;
  end if;

  return new;
end;
$$;

