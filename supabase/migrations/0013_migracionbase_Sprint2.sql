-- Recalcula el saldo y el estado de una factura considerando únicamente las
-- imputaciones cuyo origen (pago o nota de crédito) NO está anulado.
-- HU13: al anular un pago se restituye el saldo pendiente de los comprobantes
-- que tenía imputados.
create or replace function public.fn_recalcular_saldo_factura(p_factura uuid)
returns void
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  v_importe  numeric(14,2);
  v_imputado numeric(14,2);
begin
  select importe_total into v_importe
    from public.facturas_proveedor where id = p_factura;

  if v_importe is null then
    return;
  end if;

  select coalesce(sum(i.importe_imputado),0) into v_imputado
    from public.imputaciones i
    left join public.pagos_proveedor pg          on pg.id = i.pago_id
    left join public.notas_credito_proveedor nc  on nc.id = i.nota_credito_id
   where i.factura_id = p_factura
     and coalesce(pg.estado, 'registrado') <> 'anulado'
     and coalesce(nc.estado, 'pendiente')  <> 'anulada';

  if v_imputado > v_importe then
    raise exception 'La suma imputada (%) supera el importe de la factura (%)', v_imputado, v_importe;
  end if;

  update public.facturas_proveedor
     set saldo_pendiente = importe_total - v_imputado,
         estado = case
                    when estado = 'anulada' then 'anulada'
                    when importe_total - v_imputado <= 0 then 'pagada'
                    when v_imputado > 0 then 'parcialmente_pagada'
                    else 'pendiente'
                  end
   where id = p_factura;
end;
$$;


-- Igual que la anterior, pero para el saldo de una nota de crédito.
create or replace function public.fn_recalcular_saldo_nc(p_nc uuid)
returns void
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  v_importe  numeric(14,2);
  v_imputado numeric(14,2);
begin
  select importe into v_importe
    from public.notas_credito_proveedor where id = p_nc;

  if v_importe is null then
    return;
  end if;

  select coalesce(sum(importe_imputado),0) into v_imputado
    from public.imputaciones where nota_credito_id = p_nc;

  if v_imputado > v_importe then
    raise exception 'La suma imputada (%) supera el importe de la nota de crédito (%)', v_imputado, v_importe;
  end if;

  update public.notas_credito_proveedor
     set saldo_pendiente = importe - v_imputado,
         estado = case
                    when estado = 'anulada' then 'anulada'
                    when importe - v_imputado <= 0 then 'aplicada'
                    when v_imputado > 0 then 'parcialmente_aplicada'
                    else 'pendiente'
                  end
   where id = p_nc;
end;
$$;


-- HU13: la suma imputada no puede superar el importe del pago ni el de la NC.
create or replace function public.fn_aplicar_imputacion()
returns trigger
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  v_factura  uuid := coalesce(new.factura_id, old.factura_id);
  v_pago     uuid := coalesce(new.pago_id, old.pago_id);
  v_nc       uuid := coalesce(new.nota_credito_id, old.nota_credito_id);
  v_imputado numeric(14,2);
  v_importe  numeric(14,2);
begin
  if v_pago is not null then
    select importe_total into v_importe from public.pagos_proveedor where id = v_pago;
    select coalesce(sum(importe_imputado),0) into v_imputado
      from public.imputaciones where pago_id = v_pago;
    if v_imputado > v_importe then
      raise exception 'La suma imputada (%) supera el importe del pago (%)', v_imputado, v_importe;
    end if;
  end if;

  if v_nc is not null then
    perform public.fn_recalcular_saldo_nc(v_nc);
  end if;

  perform public.fn_recalcular_saldo_factura(v_factura);
  return null;
end;
$$;

drop trigger if exists trg_aplicar_imputacion on public.imputaciones;
create trigger trg_aplicar_imputacion
  after insert or update or delete on public.imputaciones
  for each row execute function public.fn_aplicar_imputacion();


-- HU13: anular un pago restituye el saldo de todas las facturas que tenía
-- imputadas. Lo mismo al anular una nota de crédito.
create or replace function public.fn_anulacion_restituye_saldo()
returns trigger
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  v_factura uuid;
begin
  if tg_table_name = 'pagos_proveedor' then
    for v_factura in select distinct factura_id from public.imputaciones where pago_id = new.id
    loop
      perform public.fn_recalcular_saldo_factura(v_factura);
    end loop;
  else
    for v_factura in select distinct factura_id from public.imputaciones where nota_credito_id = new.id
    loop
      perform public.fn_recalcular_saldo_factura(v_factura);
    end loop;
  end if;
  return null;
end;
$$;

drop trigger if exists trg_pago_anulado on public.pagos_proveedor;
create trigger trg_pago_anulado
  after update of estado on public.pagos_proveedor
  for each row when (old.estado is distinct from new.estado)
  execute function public.fn_anulacion_restituye_saldo();

