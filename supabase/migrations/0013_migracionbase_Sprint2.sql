-- El CHECK original solo admitía 'pendiente' y 'confirmada'. La HU4 exige
-- poder anular una recepción, así que hay que reemplazarlo.
alter table public.recepciones drop constraint if exists recepciones_estado_check;

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'uq_recepcion_numero') then
    alter table public.recepciones add constraint uq_recepcion_numero unique (numero);
  end if;

  if not exists (select 1 from pg_constraint where conname = 'recepciones_orden_compra_id_fkey') then
    alter table public.recepciones
      add constraint recepciones_orden_compra_id_fkey
      foreign key (orden_compra_id) references public.ordenes_compra(id) on delete restrict;
  end if;

  if not exists (select 1 from pg_constraint where conname = 'recepciones_proveedor_id_fkey') then
    alter table public.recepciones
      add constraint recepciones_proveedor_id_fkey
      foreign key (proveedor_id) references public.proveedores(id) on delete restrict;
  end if;

  if not exists (select 1 from pg_constraint where conname = 'recepciones_mov_ingreso_fkey') then
    alter table public.recepciones
      add constraint recepciones_mov_ingreso_fkey
      foreign key (movimiento_ingreso_id) references public.movimientos_stock(id);
  end if;

  if not exists (select 1 from pg_constraint where conname = 'recepciones_mov_anulacion_fkey') then
    alter table public.recepciones
      add constraint recepciones_mov_anulacion_fkey
      foreign key (movimiento_anulacion_id) references public.movimientos_stock(id);
  end if;

  if not exists (select 1 from pg_constraint where conname = 'recepciones_anulado_by_fkey') then
    alter table public.recepciones
      add constraint recepciones_anulado_by_fkey
      foreign key (anulado_by) references auth.users(id);
  end if;

  if not exists (select 1 from pg_constraint where conname = 'chk_recepcion_estado') then
    alter table public.recepciones add constraint chk_recepcion_estado
      check (estado_recepcion in ('pendiente','confirmada','anulada'));
  end if;

  if not exists (select 1 from pg_constraint where conname = 'chk_recepcion_tipo_origen') then
    alter table public.recepciones add constraint chk_recepcion_tipo_origen
      check (tipo_origen in ('orden_compra','directa'));
  end if;

  -- HU15: compra directa no lleva OC y exige motivo. Con OC es al revés.
  if not exists (select 1 from pg_constraint where conname = 'chk_recepcion_coherencia_origen') then
    alter table public.recepciones add constraint chk_recepcion_coherencia_origen
      check (
        (tipo_origen = 'orden_compra' and orden_compra_id is not null and motivo_compra_directa is null)
        or
        (tipo_origen = 'directa' and orden_compra_id is null and motivo_compra_directa is not null)
      );
  end if;

  -- HU4: anular exige usuario y motivo.
  if not exists (select 1 from pg_constraint where conname = 'chk_recepcion_anulacion') then
    alter table public.recepciones add constraint chk_recepcion_anulacion
      check (
        estado_recepcion <> 'anulada'
        or (anulado_by is not null and motivo_anulacion is not null)
      );
  end if;
end $$;

