-- HU14: cuenta corriente. Criterio contable: el proveedor es un pasivo, así que
-- las facturas van al HABER (aumentan la deuda) y los pagos y notas de crédito
-- al DEBE. saldo_acumulado positivo significa que le debemos al proveedor.
create or replace view public.vw_cuenta_corriente_proveedor as
with movimientos as (
  select f.proveedor_id,
         f.fecha_emision                         as fecha,
         'factura'::text                         as tipo_movimiento,
         f.id                                    as comprobante_id,
         concat_ws('-', f.punto_venta, f.numero) as comprobante,
         0::numeric(14,2)                        as debe,
         f.importe_total                         as haber,
         f.created_at
    from public.facturas_proveedor f
   where f.estado <> 'anulada'
  union all
  select p.proveedor_id, p.fecha, 'pago'::text, p.id,
         coalesce(p.referencia, p.numero::text),
         p.importe_total, 0::numeric(14,2), p.created_at
    from public.pagos_proveedor p
   where p.estado <> 'anulado'
  union all
  select nc.proveedor_id, nc.fecha, 'nota_credito'::text, nc.id,
         concat_ws('-', nc.punto_venta, nc.numero),
         nc.importe, 0::numeric(14,2), nc.created_at
    from public.notas_credito_proveedor nc
   where nc.estado <> 'anulada'
)
select proveedor_id, fecha, tipo_movimiento, comprobante_id, comprobante, debe, haber,
       sum(haber - debe) over (
         partition by proveedor_id
         order by fecha, created_at
         rows between unbounded preceding and current row
       ) as saldo_acumulado
  from movimientos;


-- HU3: diferencias de precio y cantidad entre factura, OC y recepción.
-- Nota: detalle_recepcion usa costo_unitario (nombre heredado del Sprint 1).
create or replace view public.vw_conciliacion_factura as
select df.factura_id,
       f.proveedor_id,
       df.producto_id,
       doc.precio_unitario                       as precio_pactado,
       df.precio_unitario                        as precio_facturado,
       df.precio_unitario - doc.precio_unitario  as diferencia_precio,
       dr.cantidad                               as cantidad_recibida,
       df.cantidad                               as cantidad_facturada,
       df.cantidad - dr.cantidad                 as diferencia_cantidad
  from public.detalle_factura_proveedor df
  join public.facturas_proveedor f on f.id = df.factura_id
  left join public.detalle_recepcion dr on dr.id = df.detalle_recepcion_id
  left join public.detalle_orden_compra doc
         on doc.id = coalesce(df.detalle_orden_compra_id, dr.orden_compra_detalle_id);


-- HU11: sugerencias de reposición según stock mínimo.
create or replace view public.vw_sugerencias_reposicion as
select p.id     as producto_id,
       p.sku,
       p.nombre as producto,
       d.id     as deposito_id,
       d.nombre as deposito,
       coalesce(s.cantidad,0) - coalesce(s.comprometido,0) as stock_disponible,
       cs.min_stock,
       cs.max_stock,
       greatest(coalesce(cs.max_stock, cs.min_stock)
                - (coalesce(s.cantidad,0) - coalesce(s.comprometido,0)), 0) as cantidad_sugerida
  from public.configuracion_stock cs
  join public.productos p on p.id = cs.producto_id
  join public.depositos d on d.id = cs.deposito_id
  left join public.stock_x_deposito s
         on s.producto_id = cs.producto_id and s.deposito_id = cs.deposito_id
 where coalesce(s.cantidad,0) - coalesce(s.comprometido,0) < cs.min_stock;


