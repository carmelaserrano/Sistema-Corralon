-- 10. ROW LEVEL SECURITY
-- ============================================================================
-- Criterio, alineado con el Sprint 1 (todas las tablas de stock ya tienen
-- rowsecurity = true):
--   · LECTURA: cualquier usuario autenticado. El sistema es interno y el
--     circuito lo exige (depósito lee órdenes de compra, compras lee
--     recepciones). Restringir lecturas por rol rompería el flujo.
--   · ESCRITURA: gobernada por usuario_permisos.
--   · anon: sin políticas, sin acceso.
-- Las tablas sin política de DELETE no admiten borrado por diseño: los
