-- ----------------------------------------------------------------------------
-- 13.1 · Migrar las políticas viejas "using (true)" de Stock/Proveedores/
--        Compras/Tesorería a "using (es_usuario_interno())". Cubre también
--        el "with check" cuando la policy es de escritura (FOR ALL), para
--        que un cliente web autenticado no pueda insertar filas ahí.
-- ----------------------------------------------------------------------------

do $$
declare
  r record;
begin
  for r in
    select tablename, policyname, with_check
    from pg_policies
    where schemaname = 'public'
      and qual = 'true'
  loop
    if r.with_check is not null then
      execute format(
        'alter policy %I on public.%I using (public.es_usuario_interno()) with check (public.es_usuario_interno())',
        r.policyname, r.tablename
      );
    else
      execute format(
        'alter policy %I on public.%I using (public.es_usuario_interno())',
        r.policyname, r.tablename
      );
    end if;
  end loop;
end $$;

