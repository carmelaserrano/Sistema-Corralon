-- autorizar_descuento(porcentaje) — versión base: autoriza siempre (no
-- valida permiso). La reemplaza S3-06, que exige 'ventas.descuento.autorizar'.
-- Corre con el token del supervisor (auth.uid() = supervisor), no con el del
-- vendedor que abrió el modal.
--
-- @param p_porcentaje numeric porcentaje a autorizar.
-- @returns uuid id de la autorización creada (válida 5 minutos).
create or replace function public.autorizar_descuento(p_porcentaje numeric)
returns uuid
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  v_id uuid;
begin
  insert into public.autorizaciones_descuento (porcentaje, autorizado_por)
  values (p_porcentaje, auth.uid())
  returning id into v_id;

  return v_id;
end;
$$;

revoke all on function public.autorizar_descuento(numeric) from public;
grant execute on function public.autorizar_descuento(numeric) to authenticated;


-- autorizacion_descuento_valida(id, porcentaje) — vigente mientras no haya
-- expirado y cubra el porcentaje solicitado.
--
-- @param p_id uuid id de la autorización.
-- @param p_porcentaje numeric porcentaje que se pretende aplicar.
-- @returns boolean true si la autorización es válida para ese porcentaje.
create or replace function public.autorizacion_descuento_valida(p_id uuid, p_porcentaje numeric)
returns boolean
language sql
stable
security invoker
set search_path = public, pg_temp
as $$
  select exists (
    select 1 from public.autorizaciones_descuento
    where id = p_id
      and porcentaje >= p_porcentaje
      and expira_at > now()
  );
