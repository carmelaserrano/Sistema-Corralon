-- comprometer_stock(deposito, items) — aumenta stock_x_deposito.comprometido
-- para cada ítem, sin tocar la cantidad física. Todo o nada: si algún ítem no
-- tiene disponible suficiente, levanta P0001/STOCK_INSUFICIENTE con producto,
-- disponible y solicitado, y no compromete nada (la excepción revierte la
-- transacción completa del llamador). SECURITY DEFINER porque la usan tanto
-- flujos internos (ventas) como el checkout web, que no tiene permiso directo
-- de escritura sobre stock_x_deposito.
--
-- @param p_deposito uuid depósito donde se compromete.
-- @param p_items jsonb array de {producto_id, cantidad}.
-- @returns void
create or replace function public.comprometer_stock(p_deposito uuid, p_items jsonb)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_item record;
  v_disponible numeric;
begin
  if p_deposito is null then
    raise exception 'El depósito es obligatorio';
  end if;

  for v_item in
    select (elem->>'producto_id')::uuid as producto_id,
           (elem->>'cantidad')::numeric as cantidad
    from jsonb_array_elements(coalesce(p_items, '[]'::jsonb)) as elem
  loop
    if v_item.producto_id is null or v_item.cantidad is null or v_item.cantidad <= 0 then
      raise exception 'Cada ítem necesita producto_id y una cantidad mayor a 0';
    end if;

    select s.cantidad - s.comprometido into v_disponible
    from public.stock_x_deposito s
    where s.producto_id = v_item.producto_id
      and s.deposito_id = p_deposito
    for update;

    if not found or v_disponible < v_item.cantidad then
      raise exception 'STOCK_INSUFICIENTE: producto % — disponible % — solicitado %',
        v_item.producto_id, coalesce(v_disponible, 0), v_item.cantidad
        using errcode = 'P0001';
    end if;

    update public.stock_x_deposito
    set comprometido = comprometido + v_item.cantidad,
        updated_at = now()
    where producto_id = v_item.producto_id
      and deposito_id = p_deposito;
  end loop;
end;
$$;

revoke all on function public.comprometer_stock(uuid, jsonb) from public;
grant execute on function public.comprometer_stock(uuid, jsonb) to authenticated;


