-- calcular_precio_venta(producto, cliente, cantidad) — versión base: precio
-- de la lista asignada al tipo de cliente, o la lista "General" si el
-- cliente es nulo o su tipo no tiene lista asignada. `p_cantidad` está en la
-- firma para que S3-06 pueda agregar descuentos por volumen sin romper a
-- quien ya la llama.
--
-- @param p_producto uuid del producto.
-- @param p_cliente uuid del cliente, o null.
-- @param p_cantidad cantidad de la línea (no usada en la versión base).
-- @returns numeric precio unitario, o null si no hay precio cargado.
create or replace function public.calcular_precio_venta(
  p_producto uuid,
  p_cliente uuid,
  p_cantidad numeric default 1
)
returns numeric
language plpgsql
stable
security invoker
set search_path = public, pg_temp
as $$
declare
  v_lista uuid;
  v_precio numeric;
begin
  if p_cliente is not null then
    select tc.lista_precio_id into v_lista
    from public.clientes c
    join public.tipos_cliente tc on tc.id = c.tipo_cliente_id
    where c.id = p_cliente;
  end if;

  if v_lista is null then
    select id into v_lista
    from public.listas_precio
    where nombre = 'General' and activo;
  end if;

  select precio into v_precio
  from public.precios_lista
  where lista_precio_id = v_lista
    and producto_id = p_producto;

  return v_precio;
end;
$$;

revoke all on function public.calcular_precio_venta(uuid, uuid, numeric) from public;
grant execute on function public.calcular_precio_venta(uuid, uuid, numeric) to authenticated;


