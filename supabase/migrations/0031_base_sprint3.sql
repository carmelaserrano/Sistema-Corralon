-- 14.4 · Ventas: 3 Pendientes + 1 Facturada con comprobante y cobro (CA-06).
-- Se omite si todavía no hay depósito o producto activo cargado.
do $$
declare
  v_deposito_id     uuid;
  v_producto_id     uuid;
  v_precio          numeric;
  v_cliente_ri      uuid;
  v_cliente_cf      uuid;
  v_punto_venta_id  uuid;
  v_medio_efectivo  uuid;
  v_venta_id        uuid;
  v_numero          bigint;
  v_comprobante_id  uuid;
  v_vendedor_id     uuid;
  i                 int;
begin
  select id into v_deposito_id from public.depositos order by created_at limit 1;
  select id into v_producto_id from public.productos where estado_producto = 'activo' order by created_at limit 1;
  select id into v_cliente_ri from public.clientes where numero_documento = '20123456786';
  select id into v_cliente_cf from public.clientes where numero_documento = '30111222';
  select id into v_punto_venta_id from public.puntos_venta where numero = '0001';
  select id into v_medio_efectivo from public.medios_pago where nombre = 'Efectivo';

  -- auth.uid() da null acá: el SQL Editor corre como postgres, sin JWT.
  -- vendedor_id es NOT NULL, así que hace falta un usuario real explícito.
  select usuario_id into v_vendedor_id from public.usuarios_internos limit 1;
  if v_vendedor_id is null then
    select id into v_vendedor_id from auth.users limit 1;
  end if;

  if v_deposito_id is null or v_producto_id is null or v_cliente_ri is null
     or v_cliente_cf is null or v_vendedor_id is null then
    raise notice 'Seed de ventas omitido: falta depósito, producto activo, cliente base o usuario.';
    return;
  end if;

  if exists (select 1 from public.ventas) then
    raise notice 'Seed de ventas omitido: ya hay ventas cargadas.';
    return;
  end if;

  select coalesce(precio, 1000) into v_precio
  from public.precios_lista pl
  join public.listas_precio lp on lp.id = pl.lista_precio_id
  where lp.nombre = 'General' and pl.producto_id = v_producto_id;

  -- 3 ventas Pendientes.
  for i in 1..3 loop
    insert into public.ventas (deposito_id, cliente_id, vendedor_id, estado, total)
    values (v_deposito_id, v_cliente_cf, v_vendedor_id, 'Pendiente', v_precio * 2)
    returning id into v_venta_id;

    insert into public.detalle_venta (venta_id, producto_id, cantidad, precio_unitario)
    values (v_venta_id, v_producto_id, 2, v_precio);
  end loop;

  -- 1 venta Facturada con comprobante y cobro.
  insert into public.ventas (deposito_id, cliente_id, vendedor_id, estado, total)
  values (v_deposito_id, v_cliente_ri, v_vendedor_id, 'Facturada', v_precio * 5)
  returning id into v_venta_id;

  insert into public.detalle_venta (venta_id, producto_id, cantidad, precio_unitario)
  values (v_venta_id, v_producto_id, 5, v_precio);

  v_numero := public.siguiente_numero_comprobante(v_punto_venta_id, 'factura', 'A');

  insert into public.comprobantes_venta (
    venta_id, tipo_comprobante, letra, punto_venta_id, numero,
    neto, iva, total, cae, cae_vencimiento
  )
  values (
    v_venta_id, 'factura', 'A', v_punto_venta_id, v_numero,
    round(v_precio * 5 / 1.21, 2), round(v_precio * 5 - v_precio * 5 / 1.21, 2), v_precio * 5,
    'HOMOLOGACIÓN', current_date + 10
  )
  returning id into v_comprobante_id;

  insert into public.cobros_venta (venta_id, total)
  values (v_venta_id, v_precio * 5)
  returning id into v_comprobante_id;

  insert into public.detalle_cobro (cobro_id, medio_pago_id, monto)
  values (v_comprobante_id, v_medio_efectivo, v_precio * 5);
end $$;

