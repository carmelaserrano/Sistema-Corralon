  for select to authenticated
  using (usuario_id = auth.uid());

-- Se lee desde la app (ver quién es interno), se administra por migración.
-- Sin policy de insert/update/delete para 'authenticated' a propósito.

create or replace function public.es_usuario_interno()
returns boolean
language sql
stable
security invoker
set search_path = public, pg_temp
as $$
  select exists (
    select 1 from public.usuarios_internos
    where usuario_id = auth.uid() and activo
  );
$$;

revoke all on function public.es_usuario_interno() from public;
grant execute on function public.es_usuario_interno() to authenticated;


